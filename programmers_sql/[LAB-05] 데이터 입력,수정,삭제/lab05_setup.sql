USE myschool;

-- 자식 테이블(LAB05_MEMBER)부터 지운다. 부모 테이블을 먼저 지우면 참조키 때문에 에러가 난다
DROP TABLE IF EXISTS LAB05_MEMBER;
DROP TABLE IF EXISTS LAB05_CLUB;

-- 동아리 (부모 테이블)
CREATE TABLE LAB05_CLUB (
    CLUB_ID   INT         NOT NULL COMMENT '동아리 번호',
    CLUB_NAME VARCHAR(30) NOT NULL COMMENT '동아리 이름',
    ROOM      VARCHAR(30) NOT NULL COMMENT '동아리방',
    FEE       INT         NOT NULL COMMENT '월 회비(원)',
    PRIMARY KEY (CLUB_ID)
) COMMENT='동아리';

-- 동아리 회원 (자식 테이블, CLUB_ID가 LAB05_CLUB의 CLUB_ID를 참조함)
CREATE TABLE LAB05_MEMBER (
    MEMBER_ID INT         NOT NULL AUTO_INCREMENT COMMENT '회원 번호',
    NAME      VARCHAR(20) NOT NULL COMMENT '이름',
    GRADE     INT         NOT NULL COMMENT '학년',
    PHONE     VARCHAR(15) NULL     COMMENT '연락처',
    STATUS    VARCHAR(10) NOT NULL COMMENT '활동 상태(활동, 휴면)',
    CLUB_ID   INT         NOT NULL COMMENT '소속 동아리 번호',
    PRIMARY KEY (MEMBER_ID),
    FOREIGN KEY (CLUB_ID) REFERENCES LAB05_CLUB (CLUB_ID)
) COMMENT='동아리 회원';

